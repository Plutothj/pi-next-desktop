const { contextBridge, ipcRenderer } = require("electron");

contextBridge.exposeInMainWorld("pi", {
  start: (cwd, sessionFile) => ipcRenderer.invoke("pi:start", { cwd, sessionFile }),
  createSession: (cwd) => ipcRenderer.invoke("pi:createSession", { cwd }),
  sessionPane: (sessionFile, cwd) => ipcRenderer.invoke("pi:sessionPane", { sessionFile, cwd }),
  sessionSnapshot: (sessionFile) => ipcRenderer.invoke("pi:sessionSnapshot", { sessionFile }),
  unobserveSession: (sessionFile) => ipcRenderer.invoke("pi:unobserveSession", { sessionFile }),
  getPlanMode: (sessionFile) => ipcRenderer.invoke("pi:getPlanMode", { sessionFile }),
  setPlanMode: (sessionFile, enabled, autoApprove, chain) =>
    ipcRenderer.invoke("pi:setPlanMode", { sessionFile, enabled, autoApprove, chain }),
  remoteTunnelStart: () => ipcRenderer.invoke("remote:tunnelStart"),
  remoteTunnelStop: () => ipcRenderer.invoke("remote:tunnelStop"),
  switchSession: (sessionFile, cwd, options) =>
    ipcRenderer.invoke("pi:switchSession", { sessionFile, cwd, ...options }),
  send: (payload) => ipcRenderer.invoke("pi:send", payload),
  pickFolder: () => ipcRenderer.invoke("pi:pickFolder"),
  sessions: () => ipcRenderer.invoke("pi:sessions"),
  searchSessions: (query) => ipcRenderer.invoke("pi:searchSessions", { query }),
  sessionView: (path) => ipcRenderer.invoke("pi:sessionView", { path }),
  deleteSession: (filePath) => ipcRenderer.invoke("pi:deleteSession", { path: filePath }),
  forkSessionAt: (entryId) => ipcRenderer.invoke("pi:forkSessionAt", { entryId }),
  respondUi: (id, values) => ipcRenderer.invoke("pi:uiRespond", { id, ...values }),
  parseAttachment: (payload) => ipcRenderer.invoke("attachments:parse", payload),
  exportHtml: () => ipcRenderer.invoke("pi:exportHtml"),
  diagExport: () => ipcRenderer.invoke("diag:export"),
  plans: {
    save: (cwd, content) => ipcRenderer.invoke("plans:save", { cwd, content }),
    list: (cwd) => ipcRenderer.invoke("plans:list", { cwd }),
    read: (cwd, file) => ipcRenderer.invoke("plans:read", { cwd, file }),
    delete: (cwd, file) => ipcRenderer.invoke("plans:delete", { cwd, file }),
  },
  stats: {
    usage: (days) => ipcRenderer.invoke("stats:usage", { days }),
  },
  updater: {
    state: () => ipcRenderer.invoke("update:state"),
    check: () => ipcRenderer.invoke("update:check"),
    download: () => ipcRenderer.invoke("update:download"),
    install: () => ipcRenderer.invoke("update:install"),
    openReleases: () => ipcRenderer.invoke("update:releases"),
  },
  // Only registered when the main process runs with PI_DEBUG.
  debugDialog: (dialog) => ipcRenderer.invoke("pi:debugDialog", dialog),
  debugWidget: (payload) => ipcRenderer.invoke("pi:debugWidget", payload),
  debugQuit: () => ipcRenderer.invoke("pi:debugQuit"),
  projects: {
    list: () => ipcRenderer.invoke("projects:list"),
    state: () => ipcRenderer.invoke("projects:state"),
    add: (dir) => ipcRenderer.invoke("projects:add", dir),
    remove: (dir) => ipcRenderer.invoke("projects:remove", dir),
  },
  reveal: (target) => ipcRenderer.invoke("pi:reveal", target),
  getThinkingPrefs: () => ipcRenderer.invoke("ui:getThinkingPrefs"),
  setThinkingPref: (payload) => ipcRenderer.invoke("ui:setThinkingPref", payload),
  showWindow: () => ipcRenderer.invoke("pi:showWindow"),
  platform: process.platform,
  // E2E 跑测试时不弹新手引导等首次启动 UI
  e2e: process.env.PI_E2E === "1",
  win: {
    minimize: () => ipcRenderer.invoke("win:minimize"),
    toggleMaximize: () => ipcRenderer.invoke("win:toggleMaximize"),
    closeApp: () => ipcRenderer.invoke("win:closeApp"),
    state: () => ipcRenderer.invoke("win:state"),
  },
  schedules: {
    list: () => ipcRenderer.invoke("schedules:list"),
    save: (payload) => ipcRenderer.invoke("schedules:save", payload),
    delete: (id) => ipcRenderer.invoke("schedules:delete", id),
  },
  board: {
    list: () => ipcRenderer.invoke("board:list"),
    run: (payload) => ipcRenderer.invoke("board:run", payload),
    stop: (id) => ipcRenderer.invoke("board:stop", id),
    message: (id, message) => ipcRenderer.invoke("board:message", { id, message }),
    abort: (id) => ipcRenderer.invoke("board:abort", id),
  },
  zoom: (delta) => ipcRenderer.invoke("ui:zoom", { delta }),
  getPref: (key) => ipcRenderer.invoke("ui:getPref", { key }),
  setPref: (key, value) => ipcRenderer.invoke("ui:setPref", { key, value }),
  zoomReset: () => ipcRenderer.invoke("ui:zoomReset"),
  zoomSet: (factor) => ipcRenderer.invoke("ui:zoomSet", { factor }),
  zoomGet: () => ipcRenderer.invoke("ui:zoomGet"),
  cfg: {
    read: (cwd) => ipcRenderer.invoke("cfg:read", { cwd }),
    saveProvider: (payload) => ipcRenderer.invoke("cfg:saveProvider", payload),
    deleteProvider: (name) => ipcRenderer.invoke("cfg:deleteProvider", name),
    fetchModels: (payload) => ipcRenderer.invoke("cfg:fetchModels", payload),
    setSetting: (patch) => ipcRenderer.invoke("cfg:setSetting", patch),
    gallery: (query, from) => ipcRenderer.invoke("cfg:gallery", { query, from }),
    readSkill: (file, cwd) => ipcRenderer.invoke("cfg:readSkill", { file, cwd }),
    deleteSkill: (dir) => ipcRenderer.invoke("cfg:deleteSkill", dir),
    setMcp: (name, enabled) => ipcRenderer.invoke("cfg:setMcp", { name, enabled }),
    savePersona: (payload) => ipcRenderer.invoke("cfg:savePersona", payload),
    savePrompt: (payload) => ipcRenderer.invoke("cfg:savePrompt", payload),
    deletePrompt: (payload) => ipcRenderer.invoke("cfg:deletePrompt", payload),
    readPrompt: (payload) => ipcRenderer.invoke("cfg:readPrompt", payload),
    setResources: (source, disabled) => ipcRenderer.invoke("cfg:setResources", { source, disabled }),
    install: (source) => ipcRenderer.invoke("cfg:install", source),
    uninstall: (source) => ipcRenderer.invoke("cfg:uninstall", source),
  },
  files: (cwd, query) => ipcRenderer.invoke("files:search", { cwd, query }),
  tree: (cwd, dir = "") => ipcRenderer.invoke("files:tree", { cwd, dir }),
  readFile: (cwd, file, abs) => ipcRenderer.invoke("files:read", { cwd, file, abs }),
  pickPreview: () => ipcRenderer.invoke("files:pickPreview"),
  debugApproveFile: (abs) => ipcRenderer.invoke("files:debugApprove", abs),
  saveAttachment: (payload) => ipcRenderer.invoke("attachments:save", payload),
  recordAttachments: (payload) => ipcRenderer.invoke("attachments:record", payload),
  listAttachments: (cwd) => ipcRenderer.invoke("attachments:list", { cwd }),
  readTable: (cwd, file, abs) => ipcRenderer.invoke("files:readTable", { cwd, file, abs }),
  writeTable: (cwd, file, abs, sheetName, rows) =>
    ipcRenderer.invoke("files:writeTable", { cwd, file, abs, sheetName, rows }),
  readDoc: (cwd, file, abs) => ipcRenderer.invoke("files:readDoc", { cwd, file, abs }),
  readPdf: (cwd, file, abs) => ipcRenderer.invoke("files:readPdf", { cwd, file, abs }),
  extractText: (cwd, file, abs) => ipcRenderer.invoke("files:extractText", { cwd, file, abs }),
  agents: (cwd) => ipcRenderer.invoke("agents:list", { cwd }),
  git: {
    status: (cwd) => ipcRenderer.invoke("git:status", { cwd }),
    branches: (cwd) => ipcRenderer.invoke("git:branches", { cwd }),
    checkout: (cwd, branch) => ipcRenderer.invoke("git:checkout", { cwd, branch }),
    diff: (cwd, file) => ipcRenderer.invoke("git:diff", { cwd, file }),
    revertFile: (cwd, file) => ipcRenderer.invoke("git:revertFile", { cwd, file }),
    revertAll: (cwd) => ipcRenderer.invoke("git:revertAll", { cwd }),
  },
  term: {
    run: (cmd, cwd, label, host) => ipcRenderer.invoke("term:run", { cmd, cwd, label, host }),
    list: () => ipcRenderer.invoke("term:list"),
    output: (id) => ipcRenderer.invoke("term:out", id),
    kill: (id) => ipcRenderer.invoke("term:kill", id),
    remove: (id) => ipcRenderer.invoke("term:remove", id),
    hosts: () => ipcRenderer.invoke("ssh:hosts"),
  },
  onEvent: (fn) => {
    const listener = (_e, record) => fn(record);
    ipcRenderer.on("pi:event", listener);
    return () => ipcRenderer.removeListener("pi:event", listener);
  },
});
